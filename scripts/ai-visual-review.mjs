#!/usr/bin/env node
/**
 * AI Visual Review — advisory only, never gates CI.
 *
 * Takes Playwright screenshot artifacts, sends them to a vision model,
 * posts the review as a PR comment. Exit code is always 0.
 *
 * Usage:
 *   node scripts/ai-visual-review.mjs --screenshots-dir <path> --pr <number>
 *
 * Required env vars:
 *   GITHUB_TOKEN       — for posting the PR comment
 *   GITHUB_REPOSITORY  — e.g. "ElasMoul/plants" (set automatically in Actions)
 *   GITHUB_MODEL_TOKEN — GitHub Models PAT for the vision API call
 *
 * Optional env vars:
 *   VISION_MODEL       — defaults to "gpt-4o"
 */

import { readFileSync, readdirSync, existsSync } from 'fs';
import { resolve, extname } from 'path';
import { parseArgs } from 'util';

const AZURE_ENDPOINT = 'https://models.inference.ai.azure.com/chat/completions';
const DEFAULT_MODEL = 'gpt-4o';

async function main() {
  const { values } = parseArgs({
    args: process.argv.slice(2),
    options: {
      'screenshots-dir': { type: 'string' },
      'pr': { type: 'string' },
    },
  });

  const screenshotsDir = values['screenshots-dir'];
  const prNumber = values['pr'];

  if (!screenshotsDir || !prNumber) {
    console.error('Usage: ai-visual-review.mjs --screenshots-dir <path> --pr <number>');
    process.exit(0); // Advisory — always exit 0
  }

  if (!existsSync(screenshotsDir)) {
    console.log(`Screenshots directory not found: ${screenshotsDir}. Skipping visual review.`);
    process.exit(0);
  }

  const token = process.env['GITHUB_MODEL_TOKEN'] || process.env['GITHUB_TOKEN'];
  const githubToken = process.env['GITHUB_TOKEN'];
  const repo = process.env['GITHUB_REPOSITORY'];
  const model = process.env['VISION_MODEL'] || DEFAULT_MODEL;

  if (!token || !githubToken || !repo) {
    console.log('Missing required env vars (GITHUB_TOKEN, GITHUB_REPOSITORY). Skipping.');
    process.exit(0);
  }

  // Collect PNG screenshots
  const screenshots = readdirSync(screenshotsDir)
    .filter(f => extname(f) === '.png')
    .slice(0, 5); // Cap at 5 to stay within token limits

  if (screenshots.length === 0) {
    console.log('No PNG screenshots found. Skipping visual review.');
    process.exit(0);
  }

  console.log(`Reviewing ${screenshots.length} screenshot(s): ${screenshots.join(', ')}`);

  // Build image_url content blocks
  const imageBlocks = screenshots.map(filename => {
    const filePath = resolve(screenshotsDir, filename);
    const data = readFileSync(filePath).toString('base64');
    return {
      type: 'image_url',
      image_url: {
        url: `data:image/png;base64,${data}`,
        detail: 'low', // Keep token usage bounded
      },
    };
  });

  const systemPrompt = `You are a UI quality reviewer for PlantPal, a plant care web app.
You receive screenshots from automated E2E tests. Your job:
1. Note any obvious layout breaks, overflow, or z-index issues.
2. Note any text that appears truncated or overlapping.
3. Note color contrast issues visible to the naked eye.
4. Confirm what looks correct.
Keep your response concise — 3–6 bullet points total. This is advisory only.`;

  const userMessage = {
    role: 'user',
    content: [
      { type: 'text', text: `Please review these ${screenshots.length} UI screenshot(s) from the PlantPal E2E suite: ${screenshots.join(', ')}` },
      ...imageBlocks,
    ],
  };

  let reviewText;
  try {
    const response = await fetch(AZURE_ENDPOINT, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${token}`,
      },
      body: JSON.stringify({
        model,
        messages: [
          { role: 'system', content: systemPrompt },
          userMessage,
        ],
        max_tokens: 512,
        temperature: 0.3,
      }),
    });

    if (!response.ok) {
      const text = await response.text();
      console.log(`Vision API returned ${response.status}. Skipping comment.\n${text}`);
      process.exit(0);
    }

    const json = await response.json();
    reviewText = json.choices?.[0]?.message?.content ?? 'No review returned.';
  } catch (err) {
    console.log(`Vision API call failed: ${err.message}. Skipping comment.`);
    process.exit(0);
  }

  // Post GitHub PR comment
  const commentBody = `## 🤖 AI Visual Review (advisory)

> This comment is generated by an AI vision model reviewing E2E screenshots.
> It is **advisory only** — it does not block merging.

${reviewText}

---
*Screenshots reviewed: ${screenshots.join(', ')} | Model: ${model}*`;

  try {
    const commentRes = await fetch(
      `https://api.github.com/repos/${repo}/issues/${prNumber}/comments`,
      {
        method: 'POST',
        headers: {
          'Authorization': `Bearer ${githubToken}`,
          'Content-Type': 'application/json',
          'Accept': 'application/vnd.github+json',
          'X-GitHub-Api-Version': '2022-11-28',
        },
        body: JSON.stringify({ body: commentBody }),
      },
    );

    if (commentRes.ok) {
      console.log(`Posted visual review comment to PR #${prNumber}.`);
    } else {
      const text = await commentRes.text();
      console.log(`Failed to post comment (${commentRes.status}): ${text}`);
    }
  } catch (err) {
    console.log(`Failed to post GitHub comment: ${err.message}`);
  }

  process.exit(0); // Always 0 — advisory only
}

main();
